import { Kysely, sql } from 'kysely';

/**
 * Everything sensitive is stored as client-side ciphertext ("1.<iv>.<ct>" or "e1.<eph>.<iv>.<ct>").
 * The server only sees ids, timestamps, roles and opaque blobs.
 */
export interface UsersTable {
  id: string;
  email: string;
  name: string;
  auth_hash: string;              // argon2id(authKey) — authKey is derived client-side, never the master password
  kdf: string;                    // JSON: { alg, salt, memory, iterations, parallelism }
  protected_user_key: string;     // user key encrypted with the master-password-derived key
  public_key: string;             // ECDH P-256 SPKI (base64)
  protected_private_key: string;  // private key encrypted with the user key
  totp_secret: string | null;
  totp_enabled: number;
  security_stamp: string;
  created_at: string;
  updated_at: string;
}

export interface SessionsTable {
  id: string;                     // sha256 of the cookie token
  user_id: string;
  user_agent: string;
  created_at: string;
  last_seen_at: string;
  expires_at: string;
}

export interface FoldersTable {
  id: string;
  user_id: string;
  data: string;
  created_at: string;
  updated_at: string;
}

export interface TeamsTable {
  id: string;
  data: string;                   // team name etc., encrypted with the team key
  created_by: string;
  created_at: string;
  updated_at: string;
}

export interface TeamMembersTable {
  team_id: string;
  user_id: string;
  role: 'owner' | 'admin' | 'editor' | 'viewer';
  protected_team_key: string;     // team key sealed to this member's public key
  created_at: string;
}

export interface ItemsTable {
  id: string;                     // generated by the client (also used as AEAD associated data)
  user_id: string | null;         // personal item owner
  team_id: string | null;         // or team item
  folder_id: string | null;
  data: string;
  revision: number;
  deleted_at: string | null;
  created_at: string;
  updated_at: string;
}

export interface Database {
  users: UsersTable;
  sessions: SessionsTable;
  folders: FoldersTable;
  teams: TeamsTable;
  team_members: TeamMembersTable;
  items: ItemsTable;
}

/** Portable migrations: the same schema builder calls run on SQLite and Postgres. */
export async function migrate(db: Kysely<Database>) {
  await db.schema
    .createTable('kv_meta').ifNotExists()
    .addColumn('key', 'varchar(64)', c => c.primaryKey())
    .addColumn('value', 'text', c => c.notNull())
    .execute();
  const row = await (db as Kysely<any>).selectFrom('kv_meta').select('value').where('key', '=', 'schema_version').executeTakeFirst();
  const version = row ? Number(row.value) : 0;

  const steps: Array<(db: Kysely<any>) => Promise<void>> = [
    async db => {
      await db.schema.createTable('users')
        .addColumn('id', 'varchar(36)', c => c.primaryKey())
        .addColumn('email', 'varchar(320)', c => c.notNull().unique())
        .addColumn('name', 'varchar(120)', c => c.notNull())
        .addColumn('auth_hash', 'text', c => c.notNull())
        .addColumn('kdf', 'text', c => c.notNull())
        .addColumn('protected_user_key', 'text', c => c.notNull())
        .addColumn('public_key', 'text', c => c.notNull())
        .addColumn('protected_private_key', 'text', c => c.notNull())
        .addColumn('totp_secret', 'text')
        .addColumn('totp_enabled', 'integer', c => c.notNull().defaultTo(0))
        .addColumn('security_stamp', 'varchar(64)', c => c.notNull())
        .addColumn('created_at', 'varchar(32)', c => c.notNull())
        .addColumn('updated_at', 'varchar(32)', c => c.notNull())
        .execute();
      await db.schema.createTable('sessions')
        .addColumn('id', 'varchar(64)', c => c.primaryKey())
        .addColumn('user_id', 'varchar(36)', c => c.notNull().references('users.id').onDelete('cascade'))
        .addColumn('user_agent', 'varchar(300)', c => c.notNull())
        .addColumn('created_at', 'varchar(32)', c => c.notNull())
        .addColumn('last_seen_at', 'varchar(32)', c => c.notNull())
        .addColumn('expires_at', 'varchar(32)', c => c.notNull())
        .execute();
      await db.schema.createIndex('sessions_user').on('sessions').column('user_id').execute();
      await db.schema.createTable('folders')
        .addColumn('id', 'varchar(36)', c => c.primaryKey())
        .addColumn('user_id', 'varchar(36)', c => c.notNull().references('users.id').onDelete('cascade'))
        .addColumn('data', 'text', c => c.notNull())
        .addColumn('created_at', 'varchar(32)', c => c.notNull())
        .addColumn('updated_at', 'varchar(32)', c => c.notNull())
        .execute();
      await db.schema.createTable('teams')
        .addColumn('id', 'varchar(36)', c => c.primaryKey())
        .addColumn('data', 'text', c => c.notNull())
        .addColumn('created_by', 'varchar(36)', c => c.notNull())
        .addColumn('created_at', 'varchar(32)', c => c.notNull())
        .addColumn('updated_at', 'varchar(32)', c => c.notNull())
        .execute();
      await db.schema.createTable('team_members')
        .addColumn('team_id', 'varchar(36)', c => c.notNull().references('teams.id').onDelete('cascade'))
        .addColumn('user_id', 'varchar(36)', c => c.notNull().references('users.id').onDelete('cascade'))
        .addColumn('role', 'varchar(16)', c => c.notNull())
        .addColumn('protected_team_key', 'text', c => c.notNull())
        .addColumn('created_at', 'varchar(32)', c => c.notNull())
        .addPrimaryKeyConstraint('team_members_pk', ['team_id', 'user_id'])
        .execute();
      await db.schema.createIndex('team_members_user').on('team_members').column('user_id').execute();
      await db.schema.createTable('items')
        .addColumn('id', 'varchar(36)', c => c.primaryKey())
        .addColumn('user_id', 'varchar(36)', c => c.references('users.id').onDelete('cascade'))
        .addColumn('team_id', 'varchar(36)', c => c.references('teams.id').onDelete('cascade'))
        .addColumn('folder_id', 'varchar(36)')
        .addColumn('data', 'text', c => c.notNull())
        .addColumn('revision', 'integer', c => c.notNull().defaultTo(1))
        .addColumn('deleted_at', 'varchar(32)')
        .addColumn('created_at', 'varchar(32)', c => c.notNull())
        .addColumn('updated_at', 'varchar(32)', c => c.notNull())
        .execute();
      await db.schema.createIndex('items_user').on('items').column('user_id').execute();
      await db.schema.createIndex('items_team').on('items').column('team_id').execute();
    },
  ];

  for (let v = version; v < steps.length; v++) {
    await steps[v](db as Kysely<any>);
    await sql`delete from kv_meta where key = 'schema_version'`.execute(db);
    await sql`insert into kv_meta (key, value) values ('schema_version', ${String(v + 1)})`.execute(db);
  }
}
